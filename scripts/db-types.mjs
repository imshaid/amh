// @ts-check
// Writes apps/web/src/lib/database.gen.ts from the local database's schema (`npm run db:types`).
// With --check it changes nothing and fails if the committed file is out of date (CI runs this).
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

import { format, resolveConfig } from "prettier";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(root, "apps", "web", "src", "lib", "database.gen.ts");
const check = process.argv.includes("--check");

let generated;
try {
  generated = execFileSync(
    join(root, "node_modules", ".bin", "supabase"),
    ["gen", "types", "typescript", "--local", "--schema", "public"],
    { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] },
  );
} catch {
  console.error("Could not read the local database. Start the stack with `npm run db:start`.");
  process.exit(1);
}

const header =
  "// Generated by `npm run db:types` from the local database's schema. Do not edit.\n\n";
const formatted = await format(header + generated, {
  ...((await resolveConfig(target)) ?? {}),
  filepath: target,
});

if (check) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // Missing counts as out of date.
  }
  if (current !== formatted) {
    console.error(
      `${relative(root, target)} does not match the migrations. Run \`npm run db:types\` and commit it.`,
    );
    process.exit(1);
  }
} else {
  writeFileSync(target, formatted);
  console.warn(`Wrote ${relative(root, target)}`);
}
